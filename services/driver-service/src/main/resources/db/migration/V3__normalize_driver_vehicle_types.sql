UPDATE driver_profiles
SET vehicle_type = CASE upper(trim(vehicle_type))
    WHEN 'MOTORBIKE' THEN 'MOTORBIKE'
    WHEN 'MOTOR BIKE' THEN 'MOTORBIKE'
    WHEN 'MOTORCYCLE' THEN 'MOTORBIKE'
    WHEN 'MOTOR CYCLE' THEN 'MOTORBIKE'
    WHEN 'XE MAY' THEN 'MOTORBIKE'
    WHEN 'XE MÁY' THEN 'MOTORBIKE'
    WHEN 'ELECTRIC_MOTORBIKE' THEN 'ELECTRIC_MOTORBIKE'
    WHEN 'ELECTRIC MOTORBIKE' THEN 'ELECTRIC_MOTORBIKE'
    WHEN 'ELECTRIC MOTOR BIKE' THEN 'ELECTRIC_MOTORBIKE'
    WHEN 'E-BIKE' THEN 'ELECTRIC_MOTORBIKE'
    WHEN 'XE MAY DIEN' THEN 'ELECTRIC_MOTORBIKE'
    WHEN 'XE MÁY ĐIỆN' THEN 'ELECTRIC_MOTORBIKE'
    WHEN 'ELECTRIC_BICYCLE' THEN 'ELECTRIC_BICYCLE'
    WHEN 'ELECTRIC BICYCLE' THEN 'ELECTRIC_BICYCLE'
    WHEN 'XE DAP DIEN' THEN 'ELECTRIC_BICYCLE'
    WHEN 'XE ĐẠP ĐIỆN' THEN 'ELECTRIC_BICYCLE'
    WHEN 'BICYCLE' THEN 'BICYCLE'
    WHEN 'BIKE' THEN 'BICYCLE'
    WHEN 'XE DAP' THEN 'BICYCLE'
    WHEN 'XE ĐẠP' THEN 'BICYCLE'
    ELSE 'MOTORBIKE'
END;
